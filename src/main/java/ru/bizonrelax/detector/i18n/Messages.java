    private Messages() {
    }

    public static String get(String lang, String key) {
        Map<String, String> dict = ALL.get(normalize(lang));
        String v = dict.get(key);
        if (v == null) v = RU.get(key);
        return v != null ? v : key;
    }

    public static String normalize(String lang) {
        if (lang == null) return "ru";
        String l = lang.toLowerCase(Locale.ROOT);
        return ALL.containsKey(l) ? l : "ru";
    }

    public static Map<String, String> dictionary(String lang) {
        return Collections.unmodifiableMap(ALL.get(normalize(lang)));
    }

    private static Map<String, String> map(String... kv) {
        Map<String, String> m = new HashMap<String, String>();
        for (int i = 0; i + 1 < kv.length; i += 2) {
            m.put(kv[i], kv[i + 1]);
        }
        return m;
    }
